  function t(key, lang = currentLang) {
    const langDict = translations[lang] || translations['en'];
    return langDict[key] || translations['en'][key] || key;
  }

  function getLang() {
    return currentLang;
  }

  function setLanguage(lang) {
    if (!languages[lang]) return;
    currentLang = lang;
    localStorage.setItem(STORAGE_KEY, lang);

    // Sync header dropdown & chat dropdown
    const headerSelect = document.getElementById('header-lang-select');
    if (headerSelect && headerSelect.value !== lang) headerSelect.value = lang;

    const chatSelect = document.getElementById('chat-lang');
    if (chatSelect && chatSelect.value !== lang) chatSelect.value = lang;

    applyTranslations();

    // Trigger custom event for other modules
    window.dispatchEvent(new CustomEvent('meteor:langchange', { detail: { lang } }));
  }

  function translateCondition(condStr) {
    if (!condStr) return condStr;
    if (currentLang === 'en') return condStr;
    const match = conditionTranslations[condStr];
    if (match && match[currentLang]) return match[currentLang];
    return condStr;
  }

  function applyTranslations() {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translated = t(key);
      if (translated) {
        if (el.tagName === 'INPUT' && el.type === 'button') {
          el.value = translated;
        } else {
          el.textContent = translated;
        }
      }
    });

    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const translated = t(key);
      if (translated) el.placeholder = translated;
    });

    const titles = document.querySelectorAll('[data-i18n-title]');
    titles.forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const translated = t(key);
      if (translated) el.title = translated;
    });
  }

  function initI18n() {
    const headerSelect = document.getElementById('header-lang-select');
    const chatSelect = document.getElementById('chat-lang');

    if (headerSelect) {
      headerSelect.value = currentLang;
      headerSelect.addEventListener('change', (e) => setLanguage(e.target.value));
    }
    if (chatSelect) {
      chatSelect.value = currentLang;
      chatSelect.addEventListener('change', (e) => setLanguage(e.target.value));
    }

    applyTranslations();
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initI18n);
  } else {
    initI18n();
  }

  return {
    languages,
    t,
    getLang,
    setLanguage,
    translateCondition,
    applyTranslations
  };
